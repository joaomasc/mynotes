import { z } from 'zod';
import { SEARCH_ENTITY_TYPES } from '../constants';
import { zDate, zDateTime, zId } from './common';
import { zNoteRole } from './content';

/* ------------------------------------------------------- AI assistant -- */

/** Longest message the user can send in one turn (characters). */
export const AI_MESSAGE_MAX = 4000;

/** Items that can be "in focus" when a conversation is started from a page. */
export const AI_CONTEXT_TYPES = ['note', 'topic', 'reading', 'document', 'concept', 'mindmap'] as const;
export type AiContextType = (typeof AI_CONTEXT_TYPES)[number];

/**
 * What the user is looking at: only the item's type and id travel; the API
 * checks that it exists and belongs to the user before reading it.
 */
export const zAiContext = z.object({
  type: z.enum(AI_CONTEXT_TYPES),
  id: zId,
  /** The topic's mind map or the graph focused on the item, instead of its page. */
  view: z.enum(['map', 'graph']).nullable().default(null),
});
export type AiContext = z.infer<typeof zAiContext>;

export const zAiChatRequest = z.object({
  conversationId: zId.nullable().default(null),
  /** Generated by the client: retrying with the same id never runs the model twice. */
  messageId: zId,
  message: z.string().trim().min(1, 'Escreva uma mensagem').max(AI_MESSAGE_MAX, `Use no máximo ${AI_MESSAGE_MAX} caracteres`),
  context: zAiContext.nullable().default(null),
});
export type AiChatRequest = z.input<typeof zAiChatRequest>;

/** A real MyNotes item the assistant read or cited (always resolved by the API). */
export const zAiSource = z.object({
  type: z.enum(SEARCH_ENTITY_TYPES),
  id: zId,
  title: z.string(),
  role: zNoteRole.nullable(),
  readingId: zId.nullable(),
  page: z.number().int().nullable(),
});
export type AiSource = z.infer<typeof zAiSource>;

/**
 * read: searches and lookups (run directly); write: reversible creations and
 * edits (run directly only when the user asked for them); sensitive: batches,
 * overwrites and moves of structures (always wait for the user's confirmation).
 */
export const AI_TOOL_KINDS = ['read', 'write', 'sensitive'] as const;
export type AiToolKind = (typeof AI_TOOL_KINDS)[number];

/** One tool call made during a turn, as shown to the user. */
export const zAiToolActivity = z.object({
  tool: z.string(),
  /** "Pesquisou “Ricardo”", "Criou a nota “…”". */
  label: z.string(),
  kind: z.enum(AI_TOOL_KINDS),
  ok: z.boolean(),
});
export type AiToolActivity = z.infer<typeof zAiToolActivity>;

export const AI_ACTION_STATUSES = ['proposed', 'executing', 'executed', 'rejected', 'failed', 'expired'] as const;
export type AiActionStatus = (typeof AI_ACTION_STATUSES)[number];

/** One line of an action preview (e.g. a topic of a tree to be created). */
export const zAiPreviewLine = z.object({
  depth: z.number().int().min(0).max(10),
  label: z.string(),
  /** new: will be created; existing: already exists and is reused; change: an edit. */
  state: z.enum(['new', 'existing', 'change']),
  detail: z.string().nullable(),
});
export type AiPreviewLine = z.infer<typeof zAiPreviewLine>;

/**
 * A write requested by the assistant. Proposals wait for the user; executed
 * actions are audit records. Only the API runs them, with the arguments it
 * validated when the model asked.
 */
export const zAiAction = z.object({
  id: zId,
  conversationId: zId.nullable(),
  tool: z.string(),
  kind: z.enum(['write', 'sensitive']),
  status: z.enum(AI_ACTION_STATUSES),
  title: z.string(),
  preview: z.array(zAiPreviewLine),
  /** Items created or changed when it ran. */
  results: z.array(zAiSource),
  error: z.string().nullable(),
  createdAt: zDateTime,
  decidedAt: zDateTime.nullable(),
  expiresAt: zDateTime.nullable(),
});
export type AiAction = z.infer<typeof zAiAction>;

export const zAiUsage = z.object({
  inputTokens: z.number().int(),
  cachedTokens: z.number().int(),
  outputTokens: z.number().int(),
  reasoningTokens: z.number().int(),
  /** Computed from the usage reported by the API and the configured prices. */
  costUsd: z.number(),
});
export type AiUsage = z.infer<typeof zAiUsage>;

/** user / assistant turns; event: a record such as "the user confirmed the action". */
export const zAiMessage = z.object({
  id: zId,
  conversationId: zId,
  role: z.enum(['user', 'assistant', 'event']),
  content: z.string(),
  sources: z.array(zAiSource),
  tools: z.array(zAiToolActivity),
  actionIds: z.array(zId),
  /** incomplete: the answer was cut (limits); error: the turn failed after doing something. */
  status: z.enum(['ok', 'incomplete', 'error']),
  usage: zAiUsage.nullable(),
  createdAt: zDateTime,
});
export type AiMessage = z.infer<typeof zAiMessage>;

export const zAiConversationSummary = z.object({
  id: zId,
  title: z.string(),
  contextType: z.enum(AI_CONTEXT_TYPES).nullable(),
  contextId: zId.nullable(),
  messageCount: z.number().int(),
  costUsd: z.number(),
  createdAt: zDateTime,
  updatedAt: zDateTime,
});
export type AiConversationSummary = z.infer<typeof zAiConversationSummary>;

export const zAiConversation = zAiConversationSummary.extend({
  messages: z.array(zAiMessage),
  actions: z.array(zAiAction),
});
export type AiConversation = z.infer<typeof zAiConversation>;

export const zAiChatResponse = z.object({
  conversation: zAiConversationSummary,
  userMessage: zAiMessage,
  assistantMessage: zAiMessage,
  /** Proposals and writes made in this turn. */
  actions: z.array(zAiAction),
  /** The same messageId was already answered: nothing ran again. */
  replayed: z.boolean(),
});
export type AiChatResponse = z.infer<typeof zAiChatResponse>;

export const zAiActionDecision = z.object({
  action: zAiAction,
  /** Record added to the conversation, read by the model in the next turns. */
  event: zAiMessage.nullable(),
});
export type AiActionDecision = z.infer<typeof zAiActionDecision>;

export const zAiUsageDay = z.object({
  day: zDate,
  requests: z.number().int(),
  inputTokens: z.number().int(),
  cachedTokens: z.number().int(),
  outputTokens: z.number().int(),
  reasoningTokens: z.number().int(),
  costUsd: z.number(),
});
export type AiUsageDay = z.infer<typeof zAiUsageDay>;

export const zAiStatus = z.object({
  /** AI_ENABLED is not "false". */
  enabled: z.boolean(),
  /** OPENAI_API_KEY is present (its value is never sent). */
  configured: z.boolean(),
  model: z.string(),
  dailyBudgetUsd: z.number().nullable(),
  spentTodayUsd: z.number(),
  limits: z.object({
    messageChars: z.number().int(),
    toolCallsPerTurn: z.number().int(),
    requestsPerMinute: z.number().int(),
  }),
  pricing: z
    .object({ inputPerMTok: z.number(), cachedInputPerMTok: z.number(), outputPerMTok: z.number() })
    .nullable(),
  /** Last 30 days (UTC), most recent first. */
  usage: z.array(zAiUsageDay),
});
export type AiStatus = z.infer<typeof zAiStatus>;
