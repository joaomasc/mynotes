-- MyNotes — 0003: AI assistant (conversations, proposed/executed actions, usage)
--
-- Additive only: no existing column, row or table is changed or removed.
--
-- The assistant never stores knowledge of its own: notes, topics, relations
-- and maps stay in their tables and are changed through the same services
-- as the app. These tables only keep:
--   ai_conversations  one chat (title, item in focus when it started, totals)
--   ai_messages       user / assistant turns and "event" records (e.g. the user
--                     confirmed an action). Text, cited sources and a summary of
--                     the tool calls — never raw tool results, prompts or secrets.
--   ai_actions        writes requested by the model: proposals waiting for the
--                     user's confirmation (validated arguments in `payload`) and
--                     the audit record of what ran and what it created.
--   ai_usage_daily    tokens and cost per UTC day, from the usage reported by the
--                     API (daily budget and the usage panel).
-- They are not part of the backup format (conversations can be deleted freely).
--
-- Rollback (manual): DROP the four tables; nothing else depends on them.

CREATE TABLE ai_conversations (
  id             TEXT PRIMARY KEY,
  user_id        TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title          TEXT NOT NULL DEFAULT '',
  context_type   TEXT CHECK (context_type IS NULL OR context_type IN ('note','topic','reading','document','concept','mindmap')),
  context_id     TEXT,
  message_count  INTEGER NOT NULL DEFAULT 0,
  input_tokens   INTEGER NOT NULL DEFAULT 0,
  output_tokens  INTEGER NOT NULL DEFAULT 0,
  cost_usd       REAL NOT NULL DEFAULT 0,
  created_at     TEXT NOT NULL,
  updated_at     TEXT NOT NULL
);
CREATE INDEX idx_ai_conversations_user ON ai_conversations(user_id, updated_at DESC);

CREATE TABLE ai_messages (
  -- User messages keep the id generated by the client (retries are deduplicated).
  id               TEXT PRIMARY KEY,
  conversation_id  TEXT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
  user_id          TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role             TEXT NOT NULL CHECK (role IN ('user','assistant','event')),
  content          TEXT NOT NULL,
  -- JSON: { sources: [...], tools: [...], actionIds: [...] }
  meta             TEXT NOT NULL DEFAULT '{}',
  status           TEXT NOT NULL DEFAULT 'ok' CHECK (status IN ('ok','incomplete','error')),
  -- The user message an assistant message answers: at most one answer per message.
  reply_to         TEXT UNIQUE,
  model            TEXT,
  input_tokens     INTEGER NOT NULL DEFAULT 0,
  cached_tokens    INTEGER NOT NULL DEFAULT 0,
  output_tokens    INTEGER NOT NULL DEFAULT 0,
  reasoning_tokens INTEGER NOT NULL DEFAULT 0,
  cost_usd         REAL NOT NULL DEFAULT 0,
  created_at       TEXT NOT NULL
);
CREATE INDEX idx_ai_messages_conversation ON ai_messages(conversation_id, created_at);
CREATE INDEX idx_ai_messages_user ON ai_messages(user_id, role, created_at);

CREATE TABLE ai_actions (
  id               TEXT PRIMARY KEY,
  user_id          TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  conversation_id  TEXT REFERENCES ai_conversations(id) ON DELETE CASCADE,
  -- Assistant message that requested it (set when the turn is saved).
  message_id       TEXT,
  tool             TEXT NOT NULL,
  kind             TEXT NOT NULL CHECK (kind IN ('write','sensitive')),
  status           TEXT NOT NULL CHECK (status IN ('proposed','executing','executed','rejected','failed','expired')),
  title            TEXT NOT NULL,
  -- JSON array of preview lines shown before confirming.
  preview          TEXT NOT NULL DEFAULT '[]',
  -- JSON: arguments validated by the API when the model asked (run on confirmation).
  payload          TEXT NOT NULL,
  -- JSON array of the items created or changed.
  results          TEXT NOT NULL DEFAULT '[]',
  error            TEXT,
  created_at       TEXT NOT NULL,
  decided_at       TEXT,
  expires_at       TEXT
);
CREATE INDEX idx_ai_actions_user ON ai_actions(user_id, status, created_at DESC);
CREATE INDEX idx_ai_actions_conversation ON ai_actions(conversation_id, created_at);

CREATE TABLE ai_usage_daily (
  user_id           TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- YYYY-MM-DD (UTC)
  day               TEXT NOT NULL,
  requests          INTEGER NOT NULL DEFAULT 0,
  input_tokens      INTEGER NOT NULL DEFAULT 0,
  cached_tokens     INTEGER NOT NULL DEFAULT 0,
  output_tokens     INTEGER NOT NULL DEFAULT 0,
  reasoning_tokens  INTEGER NOT NULL DEFAULT 0,
  cost_usd          REAL NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day)
);
